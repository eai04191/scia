/// シナリオの投稿の本文に使う、和文のダミーテキスト。
/// 意味を読ませずに行の長さや折り返しを見せるため、作った文ではなく、和文のダミーテキストの定番の、宮沢賢治「ポラーノの広場」の冒頭（パブリックドメイン）を句読点で区切って使う。
enum ScenarioDummyText {
    /// 句と、元の文でその後ろにある句読点。
    private static let clauses = [
        "あのイーハトーヴォのすきとおった風、",
        "夏でも底に冷たさをもつ青いそら、",
        "うつくしい森で飾られたモリーオ市、",
        "郊外のぎらぎらひかる草の波。",
        "またそのなかでいっしょになったたくさんのひとたち、",
        "ファゼーロとロザーロ、",
        "羊飼のミーロや、",
        "顔の赤いこどもたち、",
        "地主のテーモ、",
        "山猫博士のボーガント・デストゥパーゴなど、",
        "いまこの暗い巨きな石の建物のなかで考えていると、",
        "みんなむかし風のなつかしい青い幻燈のように思われます。",
        "では、",
        "わたくしはいつかの小さなみだしをつけながら、",
        "しずかにあの年のイーハトーヴォの五月から十月までを書きつけましょう。",
    ]

    /// `start`番目の句から`count`個の句を、元の文の句読点のままつなぐ。短文の投稿らしく、末尾の句読点は付けない。最後の句の次は最初の句に戻る。
    static func sentence(from start: Int, count: Int) -> String {
        String((0..<count).map { clauses[(start + $0) % clauses.count] }.joined().dropLast())
    }
}
#endif
